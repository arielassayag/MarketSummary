def _json_exato(value, *, counter=None, depth=0):
    """Checa tipos antes de iterar/comparar: nenhum callback de entrada."""
    if counter is None:
        counter = [0]
    counter[0] += 1
    if counter[0] > MAX_JSON_NODES or depth > MAX_DEPTH:
        raise IngressoLeituraInvalido("Limite de nós/profundidade excedido")
    t = type(value)
    if t in (type(None), bool, str):
        return
    if t is int:
        if abs(value) > 9007199254740991:
            raise IngressoLeituraInvalido("Inteiro JSON fora do limite interoperável")
        return
    if t is float:
        if not math.isfinite(value):
            raise IngressoLeituraInvalido("Número JSON não finito")
        return
    if t is list:
        for item in value:
            _json_exato(item, counter=counter, depth=depth + 1)
        return
    if t is dict:
        for key, item in value.items():
            if type(key) is not str:
                raise IngressoLeituraInvalido("Chave JSON não textual exata")
            _json_exato(item, counter=counter, depth=depth + 1)
        return
    raise IngressoLeituraInvalido("Objeto não é primitivo JSON exato")


def validar_schema_exato(value, schema):
    from jsonschema import Draft202012Validator, ValidationError, validators
    from referencing import Registry

    _json_exato(value)
    _json_exato(schema)

    def refs(node):
        if type(node) is dict:
            if "$ref" in node and not node["$ref"].startswith("#/"):
                raise IngressoLeituraInvalido("Referência externa não permitida")
            for item in node.values():
                refs(item)
        elif type(node) is list:
            for item in node:
                refs(item)

    refs(schema)

    def compilation(node):
        # evolve($schema) não pode trocar silenciosamente o validador estrito por Draft normal.
        if type(node) is dict:
            return {k: compilation(v) for k, v in node.items() if k != "$schema"}
        if type(node) is list:
            return [compilation(v) for v in node]
        return node

    native_types = {
        "integer": int,
        "number": (int, float),
        "boolean": bool,
        "string": str,
        "object": dict,
        "array": list,
        "null": type(None),
    }
    checks = {
        name: (
            lambda checker, item, expected=expected: (
                type(item) in expected if type(expected) is tuple else type(item) is expected
            )
        )
        for name, expected in native_types.items()
    }

    def const(validator, expected, instance, subschema):
        if type(instance) is not type(expected) or instance != expected:
            yield ValidationError("Constante exige tipo e valor literais")

    def enum(validator, choices, instance, subschema):
        if not any(type(instance) is type(item) and instance == item for item in choices):
            yield ValidationError("Enum exige tipo e valor literais")

    strict = validators.extend(
        Draft202012Validator,
        {"const": const, "enum": enum},
        type_checker=Draft202012Validator.TYPE_CHECKER.redefine_many(checks),
    )
    error = next(iter(strict(compilation(schema), registry=Registry()).iter_errors(value)), None)
    if error is not None:
        raise IngressoLeituraInvalido("Corpo fora do schema fechado")


def bytes_resultado(resultado: JSONFechado) -> bytes:
    _json_exato(resultado)
    return json.dumps(
        resultado, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    ).encode("utf-8")


def hash_resultado(resultado: JSONFechado) -> str:
    return hashlib.sha256(bytes_resultado(resultado)).hexdigest()


def _unsupported():
    raise FonteLeituraIndisponivel(
        "RETORNO_NATIVO_NAO_SUPORTADO", "Tipo/campo nativo não pertence ao catálogo recebido"
    )


def _canonical(value):
    from enum import EnumType

    from pydantic import BaseModel

    cls = type(value)
    if type(cls) not in (type, EnumType, type(BaseModel)):
        _unsupported()
    module_name = type.__getattribute__(cls, "__module__")
    qualname = type.__getattribute__(cls, "__qualname__")
    if type(module_name) is not str or type(qualname) is not str:
        _unsupported()
    name = module_name + "." + qualname
    expected = CATALOGO_TIPOS.get(name)
    if expected is None or name not in CATALOGO_REPRESENTACOES or ".<locals>." in name:
        _unsupported()
    module = sys.modules.get(cls.__module__)
    if module is None or vars(module).get(cls.__name__) is not cls:
        _unsupported()
    origin = vars(module).get("__file__")
    if type(origin) is not str:
        _unsupported()
    body = Path(origin).read_bytes()
    if hashlib.sha256(body).hexdigest() != CATALOGO_FONTES.get(cls.__module__):
        _unsupported()
    return expected


def serializar_valor(value) -> JSONFechado:
    """Tipos exatos e campos integrais, incluindo NaN/Decimal/índices duplicados."""
    import numpy as np
    import pandas as pd
    from pandas.core.indexes.frozen import FrozenList
    from pydantic import BaseModel

    counter = [0]

    def tz_text(tz):
        if tz is None:
            return None
        if type(tz) not in (ZoneInfo, timezone):
            _unsupported()
        return str(tz)

    def encode(x, depth=0):
        counter[0] += 1
        if counter[0] > MAX_NODES or depth > MAX_DEPTH:
            raise FonteLeituraIndisponivel("LIMITE_DE_LEITURA", "Retorno excede nós/profundidade")
        typ = type(x)

        def child(y):
            return encode(y, depth + 1)

        if x is pd.NaT:
            return {"tipo": "nat"}
        if x is pd.NA:
            return {"tipo": "pandas_na"}
        if x is None:
            return {"tipo": "nulo"}
        if typ is bool:
            return {"tipo": "bool", "valor": x}
        if typ is int:
            return {"tipo": "int", "decimal": str(x)}
        if typ is float:
            if math.isnan(x):
                return {"tipo": "float", "categoria": "nan"}
            if math.isinf(x):
                return {
                    "tipo": "float",
                    "categoria": "mais_infinito" if x > 0 else "menos_infinito",
                }
            return {"tipo": "float", "categoria": "finito", "valor": x, "hex": x.hex()}
        if typ is str:
            return {"tipo": "str", "valor": x}
        if typ is bytes:
            return {"tipo": "bytes", "base64": base64.b64encode(x).decode("ascii")}
        if typ is Decimal:
            return {"tipo": "decimal", "texto": str(x)}
        if typ is date:
            return {"tipo": "date", "iso": x.isoformat()}
        if typ is datetime:
            tz = tz_text(x.tzinfo)
            return {"tipo": "datetime", "iso": x.isoformat(), "fold": x.fold, "fuso": child(tz)}
        if typ is timedelta:
            return {
                "tipo": "timedelta",
                "dias": str(x.days),
                "segundos": str(x.seconds),
                "microssegundos": str(x.microseconds),
            }
        if typ in (PosixPath, WindowsPath):
            return {"tipo": "path", "classe": "pathlib." + typ.__name__, "valor": x.as_posix()}
        if typ in (list, tuple, FrozenList):
            return {"tipo": "list" if typ is list else "tuple", "itens": [child(y) for y in x]}
        if typ is dict:
            return {
                "tipo": "dict",
                "pares": [{"chave": child(k), "valor": child(v)} for k, v in x.items()],
            }
        if typ is pd.Timestamp:
            tz = tz_text(x.tzinfo)
            return {
                "tipo": "timestamp",
                "iso": x.isoformat(),
                "fold": x.fold,
                "fuso": child(tz),
                "resolucao": x.unit,
            }
        if typ is pd.Timedelta:
            return {"tipo": "pandas_timedelta", "iso": x.isoformat(), "resolucao": x.unit}
        if typ is pd.Period:
            return {"tipo": "period", "ordinal": str(x.ordinal), "freqstr": x.freqstr}
        if typ in (ZoneInfo, timezone):
            return child(str(x))
        scalar_types = {
            np.bool_,
            np.int8,
            np.int16,
            np.int32,
            np.int64,
            np.uint8,
            np.uint16,
            np.uint32,
            np.uint64,
            np.float16,
            np.float32,
            np.float64,
            np.str_,
            np.bytes_,
            np.datetime64,
            np.timedelta64,
        }
        if typ in scalar_types:
            return {"tipo": "numpy_scalar", "dtype": x.dtype.str, "valor": child(x.item())}
        if typ is np.ndarray:
            if x.dtype.kind not in "biufmMUSO":
                _unsupported()
            return {
                "tipo": "numpy_array",
                "dtype": x.dtype.str,
                "shape": list(x.shape),
                "valores": [child(y) for y in x.flat],
            }
        if typ is pd.Series:
            return {
                "tipo": "series",
                "nome": child(x.name),
                "dtype": str(x.dtype),
                "indice": child(x.index),
                "valores": [child(y) for y in x.array],
                "attrs": child(x.attrs),
            }
        if typ is pd.DataFrame:
            return {
                "tipo": "dataframe",
                "shape": list(x.shape),
                "indice": child(x.index),
                "colunas": child(x.columns),
                "dtypes": [str(y) for y in x.dtypes],
                "valores": [
                    [child(x.iat[i, j]) for j in range(x.shape[1])] for i in range(x.shape[0])
                ],
                "attrs": child(x.attrs),
            }
        index_types = {
            pd.Index,
            pd.RangeIndex,
            pd.DatetimeIndex,
            pd.TimedeltaIndex,
            pd.PeriodIndex,
            pd.CategoricalIndex,
            pd.MultiIndex,
        }
        if typ in index_types:

            def meta(name):
                if not hasattr(x, name):
                    return {"tipo": "atributo_ausente"}
                return child(getattr(x, name))

            return {
                "tipo": "index",
                "classe": "pandas." + typ.__name__,
                "dtype": str(x.dtype),
                "valores": [child(y) for y in x],
                "nomes": [child(y) for y in x.names],
                "attrs": meta("attrs"),
                "freq": meta("freq"),
                "tz": meta("tz"),
                "categorias": meta("categories"),
                "ordered": meta("ordered"),
                "levels": meta("levels"),
                "codes": meta("codes"),
                "inicio": meta("start"),
                "fim": meta("stop"),
                "passo": meta("step"),
            }
        offset_types = {
            pd.offsets.Day,
            pd.offsets.BusinessDay,
            pd.offsets.MonthEnd,
            pd.offsets.MonthBegin,
            pd.offsets.Week,
            pd.offsets.Hour,
            pd.offsets.Minute,
            pd.offsets.Second,
            pd.offsets.Nano,
        }
        if typ in offset_types:
            return {
                "tipo": "offset",
                "classe": "pandas.offsets." + typ.__name__,
                "n": str(x.n),
                "normalize": x.normalize,
                "kwds": child(x.kwds),
                "freqstr": x.freqstr,
            }
        expected = _canonical(x)
        name = f"{typ.__module__}.{typ.__qualname__}"
        if issubclass(typ, Enum):
            return {"tipo": "enum", "classe": name, "membro": x.name, "valor": child(x.value)}
        if issubclass(typ, BaseModel):
            names = tuple(typ.model_fields)
            if names != expected or x.__pydantic_extra__:
                _unsupported()
            return {
                "tipo": "pydantic",
                "classe": name,
                "campos": [{"nome": k, "valor": child(getattr(x, k))} for k in names],
            }
        if is_dataclass(typ):
            names = tuple(f.name for f in fields(typ))
            if names != expected:
                _unsupported()
            return {
                "tipo": "dataclass",
                "classe": name,
                "campos": [{"nome": k, "valor": child(getattr(x, k))} for k in names],
            }
        _unsupported()

    result = encode(value)
    try:
        _validar_valor_recebido(result)
    except IngressoLeituraInvalido as exc:
        raise FonteLeituraIndisponivel(
            "RETORNO_NATIVO_NAO_SUPORTADO", "Forma nativa fora do catálogo fechado"
        ) from exc
    if len(bytes_resultado(result)) > MAX_RESPONSE_BYTES:
        raise FonteLeituraIndisponivel("LIMITE_DE_LEITURA", "Retorno excede bytes")
    return result


def _validar_valor_recebido(value):
    """Confere representação nominal/forma; não reconstrói objeto nativo ou autoridade."""
    import re

    seen = [0]
    index_classes = {
        "pandas." + name
        for name in (
            "Index",
            "RangeIndex",
            "DatetimeIndex",
            "TimedeltaIndex",
            "PeriodIndex",
            "CategoricalIndex",
            "MultiIndex",
        )
    }
    offsets = {
        "pandas.offsets." + name
        for name in (
            "Day",
            "BusinessDay",
            "MonthEnd",
            "MonthBegin",
            "Week",
            "Hour",
            "Minute",
            "Second",
            "Nano",
        )
    }

    def deny():
        raise IngressoLeituraInvalido("Representação nominal/forma/dtype incoerente")

    def unwrap(node):
        return node["valor"] if node["tipo"] == "numpy_scalar" else node

    def integer(node):
        node = unwrap(node)
        if node["tipo"] != "int":
            deny()
        raw = node["decimal"]
        try:
            number = int(raw)
        except ValueError:
            deny()
        if str(number) != raw:
            deny()
        return number

    def family(dtype, numpy=False):
        if type(dtype) is not str:
            deny()
        if dtype == "|O":
            return "O"
        match = re.fullmatch(r"([<>|])([biufmMUS])(\d+)(\[[a-zA-Z0-9]+\])?", dtype)
        if match:
            endian, code, width, unit = match.groups()
            try:
                width = int(width)
            except ValueError:
                deny()
            widths = {"b": (1,), "i": (1, 2, 4, 8), "u": (1, 2, 4, 8), "f": (2, 4, 8)}
            if code in widths and width not in widths[code]:
                deny()
            if code in "biu" and width == 1:
                if endian != "|":
                    deny()
            elif code != "S" and endian not in "<>":
                deny()
            if code == "S" and endian != "|":
                deny()
            if code in "mM" and (width != 8 or unit is None):
                deny()
            if (
                code in "mM"
                and re.fullmatch(r"\[(?:[1-9][0-9]*)?(?:Y|M|W|D|h|m|s|ms|us|ns|ps|fs|as)\]", unit)
                is None
            ):
                deny()
            if code not in "mM" and unit is not None:
                deny()
            return code
        if numpy:
            deny()
        if re.fullmatch(r"(?:uint|int|Int|UInt)(?:8|16|32|64)", dtype):
            return "i"
        if re.fullmatch(r"float(?:16|32|64)|Float(?:32|64)", dtype):
            return "f"
        if dtype in ("bool", "boolean"):
            return "b"
        if dtype in ("str", "string", "string[python]", "string[pyarrow]"):
            return "U"
        if dtype in ("object", "category"):
            return "O"
        if re.fullmatch(r"datetime64\[[a-zA-Z0-9]+(?:, [^\[\]]+)?\]", dtype):
            return "M"
        if re.fullmatch(r"timedelta64\[[a-zA-Z0-9]+\]", dtype):
            return "m"
        if re.fullmatch(r"period\[[^\[\]]+\]", dtype):
            return "P"
        deny()

    def cells(dtype, values, numpy=False):
        group = family(dtype, numpy)
        allowed = {
            "b": {"bool"},
            "i": {"int"},
            "u": {"int"},
            "f": {"float"},
            "U": {"str"},
            "S": {"bytes"},
            "M": {"date", "datetime", "timestamp", "int", "nat"},
            "m": {"timedelta", "pandas_timedelta", "int", "nat"},
            "P": {"period", "nat"},
        }
        nullable = not numpy and (
            dtype in ("boolean", "str", "string", "string[python]", "string[pyarrow]")
            or re.fullmatch(r"(?:Int|UInt)(?:8|16|32|64)", dtype) is not None
            or dtype in ("Float32", "Float64")
        )
        for node in values:
            leaf = unwrap(node)
            admitted = allowed.get(group, set()) | ({"pandas_na"} if nullable else set())
            if group != "O" and leaf["tipo"] not in admitted:
                deny()
            if group in "iu" and leaf["tipo"] == "int":
                number = integer(leaf)
                width = re.fullmatch(r"[<>=|]([iu])(\d+)", dtype)
                pandas_bits = re.fullmatch(r"(uint|UInt|int|Int)(8|16|32|64)", dtype)
                bits = int(width[2]) * 8 if width else int(pandas_bits[2])
                unsigned = group == "u" or dtype.startswith(("uint", "UInt"))
                minimum = 0 if unsigned else -(1 << (bits - 1))
                maximum = (1 << bits) - 1 if unsigned else (1 << (bits - 1)) - 1
                if not minimum <= number <= maximum:
                    deny()
            if group in "biufmM" and node["tipo"] == "numpy_scalar":
                actual = family(node["dtype"], numpy=True)
                if actual != group and not (group == "i" and actual == "u"):
                    deny()
                target = re.fullmatch(r"[<>=|]([biufmM])(\d+)(\[[a-zA-Z0-9]+\])?", dtype)
                current = re.fullmatch(r"[<>=|]([biufmM])(\d+)(\[[a-zA-Z0-9]+\])?", node["dtype"])
                if target and current and target.groups() != current.groups():
                    deny()
                bits = re.fullmatch(r"(?:uint|int|Int|UInt|float|Float)(8|16|32|64)", dtype)
                if bits and current and int(bits[1]) != int(current[2]) * 8:
                    deny()

    def walk(node):
        seen[0] += 1
        if seen[0] > MAX_NODES:
            deny()
        kind = node["tipo"]
        if kind in ("dataclass", "pydantic", "enum"):
            spec = CATALOGO_REPRESENTACOES.get(node["classe"])
            if spec is None or spec["tipo"] != kind:
                deny()
            if kind == "enum":
                member = spec["membros"].get(node["membro"])
                if member is None or bytes_resultado(member) != bytes_resultado(node["valor"]):
                    deny()
            elif tuple(n["nome"] for n in node["campos"]) != tuple(spec["campos"]):
                deny()
        elif kind == "float" and node["categoria"] == "finito":
            if type(node["valor"]) is not float or node["valor"].hex() != node["hex"]:
                deny()
        elif kind == "int":
            integer(node)
        elif kind == "path":
            if node["classe"] not in ("pathlib.PosixPath", "pathlib.WindowsPath"):
                deny()
        elif kind == "offset":
            if node["classe"] not in offsets:
                deny()
        elif kind == "numpy_scalar":
            cells(node["dtype"], [node["valor"]], numpy=True)
        elif kind == "numpy_array":
            cardinality = 1
            for dim in node["shape"]:
                cardinality *= dim
                if cardinality > MAX_NODES:
                    deny()
            if cardinality != len(node["valores"]):
                deny()
            cells(node["dtype"], node["valores"], numpy=True)
        elif kind == "series":
            if node["indice"]["tipo"] != "index" or len(node["valores"]) != len(
                node["indice"]["valores"]
            ):
                deny()
            cells(node["dtype"], node["valores"])
        elif kind == "dataframe":
            rows, columns = node["shape"]
            if (
                node["indice"]["tipo"] != "index"
                or node["colunas"]["tipo"] != "index"
                or rows != len(node["valores"])
                or rows != len(node["indice"]["valores"])
                or columns != len(node["colunas"]["valores"])
                or columns != len(node["dtypes"])
                or any(len(row) != columns for row in node["valores"])
            ):
                deny()
            for j, dtype in enumerate(node["dtypes"]):
                cells(dtype, [row[j] for row in node["valores"]])
        elif kind == "index":
            cls = node["classe"]
            if cls not in index_classes:
                deny()
            required_dtype = {
                "pandas.RangeIndex": "i",
                "pandas.DatetimeIndex": "M",
                "pandas.TimedeltaIndex": "m",
                "pandas.PeriodIndex": "P",
                "pandas.MultiIndex": "O",
                "pandas.CategoricalIndex": "O",
            }.get(cls)
            if required_dtype is not None and family(node["dtype"]) != required_dtype:
                deny()
            if cls == "pandas.CategoricalIndex" and node["dtype"] != "category":
                deny()
            cells(node["dtype"], node["valores"])
            if cls == "pandas.MultiIndex":
                if node["levels"]["tipo"] != "tuple" or node["codes"]["tipo"] != "tuple":
                    deny()
                levels, codes = node["levels"]["itens"], node["codes"]["itens"]
                if len(levels) != len(codes) or len(levels) != len(node["nomes"]):
                    deny()
                for level, code in zip(levels, codes, strict=True):
                    if (
                        level["tipo"] != "index"
                        or code["tipo"] != "numpy_array"
                        or code["shape"] != [len(node["valores"])]
                    ):
                        deny()
                    for item in code["valores"]:
                        number = integer(item)
                        if number < -1 or number >= len(level["valores"]):
                            deny()
                if any(
                    v["tipo"] != "tuple" or len(v["itens"]) != len(levels) for v in node["valores"]
                ):
                    deny()
                for row_number, row in enumerate(node["valores"]):
                    for level_number, level in enumerate(levels):
                        code = integer(codes[level_number]["valores"][row_number])
                        value = unwrap(row["itens"][level_number])
                        if code == -1:
                            if value["tipo"] not in ("nat", "pandas_na") and not (
                                value["tipo"] == "float" and value["categoria"] == "nan"
                            ):
                                deny()
                        elif bytes_resultado(value) != bytes_resultado(
                            unwrap(level["valores"][code])
                        ):
                            deny()
            else:
                if len(node["nomes"]) != 1 or any(
                    node[key]["tipo"] != "atributo_ausente" for key in ("levels", "codes")
                ):
                    deny()
            if cls == "pandas.RangeIndex":
                start, stop, step = (integer(node[key]) for key in ("inicio", "fim", "passo"))
                if step == 0 or len(range(start, stop, step)) != len(node["valores"]):
                    deny()
                if any(
                    integer(item) != expected
                    for item, expected in zip(
                        node["valores"], range(start, stop, step), strict=True
                    )
                ):
                    deny()
            elif any(node[key]["tipo"] != "atributo_ausente" for key in ("inicio", "fim", "passo")):
                deny()
            if cls == "pandas.CategoricalIndex":
                if node["categorias"]["tipo"] != "index" or node["ordered"]["tipo"] != "bool":
                    deny()
            elif any(node[key]["tipo"] != "atributo_ausente" for key in ("categorias", "ordered")):
                deny()

        def descend(item):
            if type(item) is dict:
                if "tipo" in item:
                    walk(item)
                else:
                    for v in item.values():
                        descend(v)
            elif type(item) is list:
                for v in item:
                    descend(v)

        for key, item in node.items():
            if key != "tipo":
                descend(item)

    walk(value)


def validar_json_resposta(payload: JSONFechado) -> JSONFechado:
    if type(payload) is not dict:
        raise IngressoLeituraInvalido("Envelope não é dict exato")
    validar_schema_exato(payload, schema_saida())
    if payload["autoridade_operacional"] is not False:
        raise IngressoLeituraInvalido("Envelope de leitura não concede autoridade")
    if payload["status"] == "disponivel":
        if payload["resultado"] is None or payload["falha"] is not None:
            raise IngressoLeituraInvalido("Discriminador de sucesso inconsistente")
        _validar_valor_recebido(payload["resultado"])
        if hash_resultado(payload["resultado"]) != payload["resultado_sha256"]:
            raise IngressoLeituraInvalido("Hash de transporte divergente")
    elif (
        payload["resultado"] is not None
        or payload["resultado_sha256"] is not None
        or payload["falha"] is None
    ):
        raise IngressoLeituraInvalido("Discriminador de falha inconsistente")
    raw = json.dumps(payload, ensure_ascii=False, allow_nan=False, separators=(",", ":")).encode()
    if len(raw) > MAX_RESPONSE_BYTES:
        raise IngressoLeituraInvalido("Envelope excede bytes")
    return json.loads(raw)


def serializar_resposta(resposta: RespostaConsulta) -> JSONFechado:
    if type(resposta) is not RespostaConsulta:
        raise IngressoLeituraInvalido("Resposta de classe diferente")
    raw = {f.name: object.__getattribute__(resposta, f.name) for f in fields(RespostaConsulta)}
    if type(raw["readset"]) is not tuple or type(raw["hashes_nativos"]) is not tuple:
        raise IngressoLeituraInvalido("Coleções do envelope não são tuplas exatas")
    refs = []
    for ref in raw["readset"]:
        if type(ref) is not ReferenciaFonte:
            raise IngressoLeituraInvalido("Referência de classe diferente")
        item = {f.name: object.__getattribute__(ref, f.name) for f in fields(ReferenciaFonte)}
        _json_exato(item)
        refs.append(item)
    raw["readset"] = refs
    if raw["falha"] is not None:
        failure = raw["falha"]
        if type(failure) is not FalhaLeitura or type(failure.membros) is not tuple:
            raise IngressoLeituraInvalido("Falha de classe/coleção diferente")
        raw["falha"] = {
            f.name: object.__getattribute__(failure, f.name) for f in fields(FalhaLeitura)
        }
        raw["falha"]["membros"] = list(failure.membros)
    pairs = []
    for pair in raw["hashes_nativos"]:
        if type(pair) is not tuple or len(pair) != 2:
            raise IngressoLeituraInvalido("Par de hash inválido")
        pairs.append({"nome": pair[0], "sha256": pair[1]})
    raw["hashes_nativos"] = pairs
    return validar_json_resposta(raw)
